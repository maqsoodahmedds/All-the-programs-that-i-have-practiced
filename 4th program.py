# This is program of List
fruits = ["Apple","Banana","Mango","Banana"]
print(fruits)
fruits.append("Orange") # append means to add item
print(fruits)
fruits.insert(1,"Grapes") # insert means to put the grapes in place 1
print(fruits)
fruits.remove("Banana") # remove means to delete  Banana item
print(fruits)
fruits.pop() # pop means to delete last item 
print(fruits)
fruits.sort() # sort means to give thatt list
print(fruits)