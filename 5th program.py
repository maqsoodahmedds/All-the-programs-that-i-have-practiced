# This is program of list
fruits = ["Apple","Banana","Mango","Banana"]
print(fruits)
fruits.append("Orange")  # append means to add item
print(fruits)
fruits.insert(1,"Grapes") # insert means to put the grapes in 1 place 
print(fruits)
fruits.remove("Banana") # remove means to delete one item 
print(fruits)
fruits.pop() # pop means to delete last item 
print(fruits)
fruits.sort() # sort that list
print(fruits)
for fruit in fruits:
    print(fruit)
